# Shared by scripts/icon.sh, scripts/dmg.sh and scripts/notarize.sh (sourced, zsh).
# Expects $ROOT. Reads the project config through tools/packaging/pkg.py (PKG_* variables).

# The design files the tools compile with, so icon and DMG use the app's own accent palette,
# type scale and spacing (one source, no copied hex values).
TOOL_KIT_SOURCES=(
  App/Sources/Kit/Design/Theme.swift
  App/Sources/Kit/Design/Tokens.swift
)

pkg_env() {
  # Loads PKG_* variables from starter.json (and the environment overrides pkg.py documents).
  local out
  out="$(python3 "$ROOT/tools/packaging/pkg.py" env)" || return 1
  eval "$out"
}

build_tool() {
  # build_tool <name> <source>...  ->  build/tools/<name>, rebuilt only when a source changed.
  # Tools are small command line programs that run on this Mac while building (never shipped).
  local name="$1"; shift
  local out="$ROOT/build/tools/$name"
  local shim="$ROOT/build/tools/ToolConfig.swift"
  mkdir -p "$ROOT/build/tools"
  # Theme.swift and Tokens.swift default to AppConfig.accent; the tools get a one-line stand-in
  # (the real AppConfig pulls in the whole app). Rewritten only when the accent changes.
  local shim_text="// Generated by tools/lib/packaging.sh. Do not edit.
nonisolated enum AppConfig { static let accent: AccentName = .$PKG_ACCENT }"
  if [[ ! -f "$shim" || "$(<"$shim")" != "$shim_text" ]]; then print -r -- "$shim_text" > "$shim"; fi
  local sources=("$@" "${TOOL_KIT_SOURCES[@]/#/$ROOT/}" "$shim")
  local stale=0 src
  if [[ ! -x "$out" ]]; then stale=1; else
    for src in "${sources[@]}"; do [[ "$src" -nt "$out" ]] && { stale=1; break; }; done
  fi
  (( stale )) || return 0
  source "$ROOT/scripts/lib/swift.sh"
  use_sdk
  local log="$ROOT/build/tools/$name.log"
  if ! swiftc -sdk "$SDKROOT" -swift-version 6 -default-isolation MainActor -parse-as-library -O \
      -target "arm64-apple-macosx$PKG_MIN_MACOS" -module-name "Tool_${name//-/_}" \
      -module-cache-path "$ROOT/build/cache/modules" \
      -o "$out.tmp" "${sources[@]}" >"$log" 2>&1; then
    cat "$log" >&2
    print -u2 "packaging: building the $name tool failed (log: build/tools/$name.log)"
    return 1
  fi
  mv -f "$out.tmp" "$out"
}

macho_files() {
  # Prints every Mach-O file inside a bundle except its main executable, deepest path first,
  # so nested code is signed before the code that contains it.
  local app="$1" main="$1/Contents/MacOS/${${1:t}%.app}"
  python3 "$ROOT/tools/packaging/pkg.py" macho "$app" | while IFS= read -r f; do
    [[ "$f" == "$main" ]] || print -r -- "$f"
  done
}

_sign() {
  # codesign without its "replacing existing signature" chatter; the output shows on failure.
  local out
  if ! out="$(codesign "$@" 2>&1)"; then
    print -u2 -r -- "$out"
    print -u2 -r -- "packaging: signing ${@[-1]} failed"
    return 1
  fi
}

sign_app() {
  # sign_app <app> <identity> [entitlements]: inside out. Nested bundles and loose Mach-O files
  # first (no --deep: it skips code in Resources/ and signs helpers with the wrong options),
  # then the app. Ad hoc ("-") never uses the hardened runtime: it would block nothing and only
  # make debugging harder. A Developer ID always does, with a secure timestamp (notarization needs both).
  local app="$1" identity="$2" ents="${3:-}" f
  local -a base
  if [[ "$identity" == "-" ]]; then base=(--force --sign -)
  else base=(--force --options runtime --timestamp --sign "$identity"); fi
  for f in ${(f)"$(macho_files "$app")"} \
           ${(f)"$(find "$app/Contents" -depth \( -name '*.app' -o -name '*.framework' -o -name '*.xpc' -o -name '*.appex' \) -type d 2>/dev/null)"}; do
    _sign "${base[@]}" "$f" || return 1
  done
  if [[ -n "$ents" ]]; then base+=(--entitlements "$ents"); fi
  _sign "${base[@]}" "$app" || return 1
  codesign --verify --strict --deep "$app" || { print -u2 "packaging: signature check failed for $app"; return 1; }
}
